/**
 * Hidden system bars while [isFullscreen]; with [lockLandscape] the screen is also forced to
 * landscape. Restored when it ends or the screen leaves.
 */
@Composable
internal fun FullscreenEffect(isFullscreen: Boolean, lockLandscape: Boolean) {
    val view = LocalView.current
    DisposableEffect(isFullscreen, lockLandscape) {
        val activity = view.context.findActivity()
        val controller = activity?.window?.let { WindowCompat.getInsetsController(it, view) }
        if (isFullscreen) {
            if (lockLandscape) activity?.requestedOrientation = ActivityInfo.SCREEN_ORIENTATION_SENSOR_LANDSCAPE
            controller?.systemBarsBehavior = WindowInsetsControllerCompat.BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE
            controller?.hide(WindowInsetsCompat.Type.systemBars())
        }
        onDispose {
            if (isFullscreen) {
                if (lockLandscape) activity?.requestedOrientation = ActivityInfo.SCREEN_ORIENTATION_UNSPECIFIED
                controller?.show(WindowInsetsCompat.Type.systemBars())
                activity?.window?.let { window ->
                    window.attributes = window.attributes.apply {
                        screenBrightness = WindowManager.LayoutParams.BRIGHTNESS_OVERRIDE_NONE
                    }
                }
            }
        }
    }
}

internal tailrec fun Context.findActivity(): Activity? = when (this) {
    is Activity -> this
    is ContextWrapper -> baseContext.findActivity()
    else -> null
}

/** The video's captions as a scrolling transcript; tapping a line seeks. */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
internal fun TranscriptSheet(
    tracks: List<SubtitleOption>,
    preferredTag: String?,
    positionMs: Long,
    onSeek: (Long) -> Unit,
    onDismiss: () -> Unit
) {
    val defaultTrack = remember(tracks, preferredTag) {
        tracks.firstOrNull { it.languageTag == preferredTag }
            ?: tracks.firstOrNull { !it.autoGenerated && it.languageTag.startsWith(Locale.getDefault().language) }
            ?: tracks.firstOrNull { !it.autoGenerated } ?: tracks.first()
    }
    var track by remember { mutableStateOf(defaultTrack) }
    var lines by remember(track) { mutableStateOf<FeedState<List<WatchExtras.TranscriptLine>>>(FeedState.Loading) }
    LaunchedEffect(track) {
        lines = withContext(Dispatchers.IO) { runCatching { WatchExtras.transcript(track) } }.toFeedState()
    }
    val listState = rememberLazyListState()
    val data = (lines as? FeedState.Data)?.value.orEmpty()
    val current = data.indexOfLast { it.startMs <= positionMs }
    LaunchedEffect(current) {
        if (current > 2 && !listState.isScrollInProgress) listState.animateScrollToItem(current - 2)
    }
    ModalBottomSheet(onDismissRequest = onDismiss, containerColor = OriginalColors.Sheet, contentColor = OriginalColors.TextPrimary) {
        GlassWindowBlur()
        Column(modifier = Modifier.fillMaxHeight(0.75f)) {
            Text(
                text = "Transcript",
                fontSize = 18.sp,
                fontWeight = FontWeight.Bold,
                color = OriginalColors.TextPrimary,
                modifier = Modifier.padding(horizontal = 16.dp, vertical = 8.dp)
            )
            if (tracks.size > 1) {
                OriginalFilterChips(
                    labels = tracks.map { it.label },
                    selected = track.label,
                    onSelect = { label -> tracks.firstOrNull { it.label == label }?.let { track = it } },
                    unselectedColor = OriginalColors.Chip
                )
            }
            when (val state = lines) {
                is FeedState.Loading -> OriginalLoading()
                is FeedState.Error -> OriginalError(message = state.message, onRetry = { lines = FeedState.Loading; track = track.copy() })
                is FeedState.Data -> LazyColumn(state = listState, contentPadding = PaddingValues(bottom = 24.dp)) {
                    itemsIndexed(state.value) { index, line ->
                        Row(
                            modifier = Modifier
                                .fillMaxWidth()
                                .background(if (index == current) OriginalColors.Chip else Color.Transparent)
                                .clickable { onSeek(line.startMs) }
                                .padding(horizontal = 16.dp, vertical = 8.dp)
                        ) {
                            Text(
                                text = formatVideoDuration(line.startMs),
                                fontSize = 13.sp,
                                color = OriginalColors.Accent,
                                modifier = Modifier.width(56.dp)
                            )
                            Text(text = line.text, fontSize = 14.sp, color = OriginalColors.TextPrimary)
                        }
                    }
                }
            }
        }
    }
}

/** Live chat (or its replay, kept in step with the video), polled while the sheet is open. */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
internal fun LiveChatSheet(start: LiveChat.Start, positionMs: () -> Long, onDismiss: () -> Unit) {
    var messages by remember(start) { mutableStateOf<List<LiveChat.Message>>(emptyList()) }
    var error by remember { mutableStateOf<String?>(null) }
    val listState = rememberLazyListState()
    LaunchedEffect(start) {
        var token: String? = start.continuation
        while (token != null) {
            val result = withContext(Dispatchers.IO) { runCatching { LiveChat.poll(token.orEmpty(), start.replay, positionMs()) } }
            val page = result.getOrNull()
            if (page == null) {
                error = result.exceptionOrNull()?.message ?: "Couldn't load the chat"
                delay(5000)
                continue
            }
            error = null
            if (page.messages.isNotEmpty()) {
                messages = (messages + page.messages).distinctBy { it.id.ifEmpty { it.author + it.text + it.offsetMs } }.takeLast(300)
            }
            token = page.continuation
            delay(page.pollAfterMs)
        }
    }
    val shown = if (start.replay) messages.filter { it.offsetMs <= positionMs() } else messages
    LaunchedEffect(shown.size) { if (shown.isNotEmpty()) listState.animateScrollToItem(shown.size - 1) }
    ModalBottomSheet(onDismissRequest = onDismiss, containerColor = OriginalColors.Sheet, contentColor = OriginalColors.TextPrimary) {
        GlassWindowBlur()
        Column(modifier = Modifier.fillMaxHeight(0.75f)) {
            Text(
                text = if (start.replay) "Live chat replay" else "Live chat",
                fontSize = 18.sp,
                fontWeight = FontWeight.Bold,
                modifier = Modifier.padding(horizontal = 16.dp, vertical = 8.dp)
            )
            error?.let { Text(it, fontSize = 12.sp, color = OriginalColors.TextSecondary, modifier = Modifier.padding(horizontal = 16.dp)) }
            if (shown.isEmpty()) {
                Text("Waiting for messages...", fontSize = 14.sp, color = OriginalColors.TextSecondary, modifier = Modifier.padding(16.dp))
            }
            LazyColumn(state = listState, contentPadding = PaddingValues(bottom = 24.dp)) {
                items(shown) { m ->
                    Row(
                        modifier = Modifier
                            .fillMaxWidth()
                            .background(if (m.amount.isNotEmpty()) Color(0x331E88E5) else Color.Transparent)
                            .padding(horizontal = 16.dp, vertical = 6.dp),
                        verticalAlignment = Alignment.Top
                    ) {
                        AsyncImage(
                            model = m.avatarUrl,
                            contentDescription = null,
                            contentScale = ContentScale.Crop,
                            modifier = Modifier.size(24.dp).clip(CircleShape)
                        )
                        Spacer(Modifier.width(8.dp))
                        Column {
                            Text(
                                text = m.author + if (m.amount.isNotEmpty()) "  ${m.amount}" else "",
                                fontSize = 12.sp,
                                fontWeight = FontWeight.Medium,
                                color = when {
                                    m.isModerator -> Color(0xFF5E84F1)
                                    m.isMember -> Color(0xFF2BA640)
                                    else -> OriginalColors.TextSecondary
                                }
                            )
                            if (m.text.isNotEmpty()) Text(m.text, fontSize = 14.sp, color = OriginalColors.TextPrimary)
                        }
                    }
                }
            }
        }
    }
}
